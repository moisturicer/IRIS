// Writes e2e/.env.e2e: the one environment file the IR-631 stack reads, both
// for Compose interpolation (DB_*) and as every Django service's env_file.
//
// Why generated rather than committed: production settings refuse to start
// without SECRET_KEY, a recovery HMAC key and a Fernet key, and CLAUDE.md
// forbids committing secrets -- even throwaway ones, because a committed key
// gets copied into a real .env sooner or later. Each run gets fresh random
// values instead. The stack is synthetic and torn down after the run.
//
// Why a separate file rather than backend/.env: a developer's backend/.env
// carries DEBUG=True and, often, real Voyage/LLM keys. The pinned run must use
// production settings and must not spend credits by accident, so it never
// reads that file. Provider keys for a later, approved Ask IRIS run go in
// e2e/.env.e2e.local (gitignored), which is appended when present.
//
//   node e2e/scripts/make-env.mjs [--port 8090] [--force]
//
// Idempotent: an existing e2e/.env.e2e is kept unless --force, so a stack
// whose database was created with one password is not handed another.

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const e2eDir = path.resolve(here, "..");
const target = path.join(e2eDir, ".env.e2e");
const local = path.join(e2eDir, ".env.e2e.local");

const argv = process.argv.slice(2);
const force = argv.includes("--force");
const portIndex = argv.indexOf("--port");
const port = portIndex >= 0 ? argv[portIndex + 1] : process.env.E2E_PORT ?? "8090";

if (existsSync(target) && !force) {
  console.log(`kept ${path.relative(process.cwd(), target)} (use --force to regenerate)`);
  process.exit(0);
}

const hex = (bytes) => randomBytes(bytes).toString("hex");
// cryptography.Fernet expects urlsafe base64 of 32 bytes, padding included.
const fernetKey = randomBytes(32).toString("base64").replace(/\+/g, "-").replace(/\//g, "_");

const origin = `https://localhost:${port}`;

const lines = [
  "# Generated by e2e/scripts/make-env.mjs for the IR-631 core-journey stack.",
  "# Throwaway values for a synthetic stack. Never copy them into a real .env.",
  `E2E_PORT=${port}`,
  "",
  "# Compose interpolation and Django's database settings",
  "DB_NAME=iris_e2e",
  "DB_USER=iris_e2e",
  `DB_PASSWORD=${hex(16)}`,
  `REDIS_PASSWORD=${hex(16)}`,
  "",
  "# Production settings' required keys (config/settings/production.py)",
  `SECRET_KEY=${hex(32)}`,
  "ALLOWED_HOSTS=localhost,127.0.0.1,backend",
  `CORS_ALLOWED_ORIGINS=${origin}`,
  "TRUSTED_PROXY_COUNT=1",
  // Production settings require it (IR-660); every journey registers @cit.edu.
  "REGISTRATION_EMAIL_DOMAINS=cit.edu",
  // Required by the production file; its caddy service is off in this stack.
  "IRIS_DOMAIN=localhost",
  // An https origin is a production requirement for recovery links. Nothing
  // listens on it with TLS: the run reads links from Mailpit and follows only
  // their path on the plain-HTTP base URL (see e2e/README.md, Limitations).
  `FRONTEND_URL=${origin}`,
  "",
  "# Mail goes to Mailpit inside the stack, never out of it",
  "EMAIL_HOST=mailpit",
  "EMAIL_PORT=1025",
  "EMAIL_USE_TLS=False",
  "EMAIL_HOST_USER=iris-e2e@cit.edu",
  `EMAIL_HOST_PASSWORD=${hex(8)}`,
  "",
  "# Account recovery (ADR-045 §8)",
  `RECOVERY_COUNTER_HMAC_KEY=${hex(32)}`,
  `RECOVERY_MAIL_ENCRYPTION_KEY=${fernetKey}`,
  "",
  "# DRF's per-minute request bursts (config/settings/base.py, IR-999), raised",
  "# for this stack only. Behind nginx every signed-out request -- each sign-in,",
  "# signup and the signup form's own lookups -- comes from one address, and a",
  "# run is faster than a person. No acceptance criterion measures these",
  "# throttles; the lockout under test is axes', which is left at its default",
  "# of three failures. A run record states this deviation.",
  "API_THROTTLE_ANON_BURST=6000/minute",
  "API_THROTTLE_USER_BURST=6000/minute",
  "API_THROTTLE_LOGIN_BURST=6000/minute",
  "API_THROTTLE_REGISTER_BURST=6000/minute",
  "# The lockout is off by default for now (IR-865); the lifecycle journey",
  "# checks it, so this stack keeps it on.",
  "AXES_ENABLED=True",
  "",
  "# PDF intake refuses every PDF unless these are set (IR-831). The candidate",
  "# values from docs/engineering/PDF_INTAKE.md. A run here doesn't verify them",
  "# on real papers, which that document still requires of a deployment.",
  "PDF_VALIDATION_WALL_SECONDS=10",
  "PDF_VALIDATION_MEMORY_MIB=256",
  "PDF_VALIDATION_MAX_PAGES=1000",
  "PDF_VALIDATION_MAX_OBJECTS=200000",
  "PDF_VALIDATION_MAX_DEPTH=100",
  "",
  "# Production settings refuse to start without LlamaParse (IR-843). A",
  "# placeholder: no journey needs a paper read, and any read fails.",
  "LLAMAPARSE_API_KEY=e2e-placeholder-not-a-key",
  "LLAMAPARSE_VERSION=2026-09-28",
  "",
];

let content = lines.join("\n");
if (existsSync(local)) {
  content += `\n# Appended from ${path.basename(local)}\n${readFileSync(local, "utf8")}\n`;
}

writeFileSync(target, content, { mode: 0o600 });
console.log(`wrote ${path.relative(process.cwd(), target)} for ${origin}`);
